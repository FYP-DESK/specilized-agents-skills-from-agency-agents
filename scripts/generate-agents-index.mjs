// Generate AGENTS_INDEX.json from .opencode/agents/*.md
// Zero dependencies. Run: node scripts/generate-agents-index.mjs
// Re-run after every change to the agents directory, then commit both together.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const agentsDir = path.join(root, ".opencode", "agents");
const outFile = path.join(root, "AGENTS_INDEX.json");

const CATEGORY_ORDER = [
  "academic", "accounts", "agents", "automation", "blender", "business",
  "change", "corporate", "customer", "data", "design", "economy",
  "engineering", "esg", "finance", "game", "gis", "godot", "government",
  "grant", "healthcare", "hospitality", "hr", "identity", "language",
  "legal", "level", "loan", "lsp", "macos", "ma", "marketing", "medical",
  "narrative", "operations", "organizational", "paid", "personal",
  "product", "project", "real", "recruitment", "report", "research",
  "resume", "retail", "roblox", "sales", "security", "specialized",
  "study", "supply", "support", "technical", "terminal", "testing",
  "unity", "unreal", "visionos", "xr", "zk",
];

function categoryOf(file) {
  const base = path.basename(file, ".md");
  for (const c of CATEGORY_ORDER) {
    if (base.startsWith(c + "-")) return c;
  }
  return base.startsWith("agentic") ? "agentic" : "general";
}

function descriptionOf(content) {
  // frontmatter description is the highest-quality one-line summary
  const m = content.match(/^---\n([\s\S]*?)\n---/);
  if (m) {
    const dm = m[1].match(/^description:\s*(.+)$/m);
    if (dm) return dm[1].trim();
  }
  // fallback: first non-heading, non-quote paragraph line
  const lines = content.split("\n");
  for (const line of lines.slice(1)) {
    const t = line.trim();
    if (t && !t.startsWith("#") && !t.startsWith(">") && !t.startsWith("---")) {
      return t.replace(/["\\]/g, "").slice(0, 240);
    }
  }
  return "Specialized domain agent instructions.";
}

function titleOf(content, fallback) {
  const m = content.match(/^---\n[\s\S]*?\nname:\s*(.+)$/m);
  if (m) return m[1].trim();
  const h1 = content.match(/^#\s+(.+)$/m);
  if (h1) return h1[1].trim();
  return fallback;
}

const files = fs
  .readdirSync(agentsDir)
  .filter((f) => f.endsWith(".md"))
  .sort((a, b) => a.localeCompare(b));

const agents = files.map((file) => {
  const content = fs.readFileSync(path.join(agentsDir, file), "utf8");
  const base = path.basename(file, ".md");
  return {
    name: base,
    title: titleOf(content, base),
    category: categoryOf(file),
    description: descriptionOf(content),
    path: `.opencode/agents/${file}`,
  };
});

const byCategory = {};
for (const a of agents) {
  (byCategory[a.category] ||= []).push(a.name);
}

const index = {
  note: "Machine-generated by scripts/generate-agents-index.mjs. Do not edit by hand — re-run the script instead.",
  generatedAt: new Date().toISOString().slice(0, 10),
  total: agents.length,
  source: "https://github.com/FYP-DESK/specilized-agents-skills-from-agency-agents",
  usage:
    "GET the raw index, pick ONE agent by category or description match, then GET only that agent's raw markdown file.",
  rawBase: "https://raw.githubusercontent.com/FYP-DESK/specilized-agents-skills-from-agency-agents/main",
  categories: Object.fromEntries(
    Object.entries(byCategory).map(([k, v]) => [k, v.length]),
  ),
  agents,
};

fs.writeFileSync(outFile, JSON.stringify(index, null, 2) + "\n");
console.log(`AGENTS_INDEX.json written: ${agents.length} agents, ${Object.keys(byCategory).length} categories.`);
